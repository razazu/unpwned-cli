import { afterEach, describe, expect, it, vi } from 'vitest'
import { blockedResult, describeInterference, detectInterference, fetchPage } from './interference.js'

function headers(init: Record<string, string> = {}): Headers {
  return new Headers(init)
}

describe('detectInterference', () => {
  it('returns null for a normal page', () => {
    expect(detectInterference(200, headers({ server: 'cloudflare' }), '<html>Welcome</html>')).toBeNull()
  })

  it('returns null for a plain 403 with no block markers', () => {
    expect(detectInterference(403, headers(), '<html>Sign in to continue</html>')).toBeNull()
  })

  it('returns null for a 503 maintenance page', () => {
    expect(detectInterference(503, headers(), '<html>Back soon, we are deploying.</html>')).toBeNull()
  })

  it('ignores block wording on a successful response', () => {
    expect(detectInterference(200, headers(), 'How to fix an Access Denied error')).toBeNull()
  })

  it('ignores a DataDome header on a successful response', () => {
    expect(detectInterference(200, headers({ 'x-datadome': 'protected' }), '<html>ok</html>')).toBeNull()
  })

  it('detects a Cloudflare challenge from the cf-mitigated header', () => {
    expect(detectInterference(403, headers({ 'cf-mitigated': 'challenge' }), '')).toEqual({
      status: 403,
      provider: 'Cloudflare',
      reason: 'challenge',
    })
  })

  it('detects a Vercel challenge from the x-vercel-mitigated header', () => {
    expect(detectInterference(403, headers({ 'x-vercel-mitigated': 'challenge' }), '')).toEqual({
      status: 403,
      provider: 'Vercel',
      reason: 'challenge',
    })
  })

  it('detects a Vercel deny as a block', () => {
    expect(detectInterference(403, headers({ 'x-vercel-mitigated': 'deny' }), '')?.reason).toBe('blocked')
  })

  it('detects a Sucuri block from its header', () => {
    expect(detectInterference(403, headers({ 'x-sucuri-block': 'BL001' }), '')?.provider).toBe('Sucuri')
  })

  it('detects an AWS WAF challenge and block from its header', () => {
    expect(detectInterference(202, headers({ 'x-amzn-waf-action': 'challenge' }), '')).toEqual({
      status: 202,
      provider: 'AWS WAF',
      reason: 'challenge',
    })
    expect(detectInterference(403, headers({ 'x-amzn-waf-action': 'block' }), '')?.reason).toBe('blocked')
  })

  it('detects a DataDome block', () => {
    expect(detectInterference(403, headers({ 'x-datadome': 'protected' }), '')?.provider).toBe('DataDome')
  })

  it('detects a Cloudflare block page from its body', () => {
    const body = '<title>Attention Required! | Cloudflare</title><h1>Sorry, you have been blocked</h1>'
    expect(detectInterference(403, headers({ server: 'cloudflare' }), body)).toEqual({
      status: 403,
      provider: 'Cloudflare',
      reason: 'blocked',
    })
  })

  it('detects a Cloudflare firewall error code', () => {
    expect(detectInterference(403, headers(), 'error code: 1020')?.provider).toBe('Cloudflare')
  })

  it('detects a Cloudflare interstitial from its body', () => {
    const body = '<title>Just a moment...</title><script src="/cdn-cgi/challenge-platform/h/b/orchestrate"></script>'
    expect(detectInterference(503, headers(), body)?.reason).toBe('challenge')
  })

  it('detects an Akamai block page', () => {
    const body = '<h1>Access Denied</h1>You do not have permission. Reference #18.2f1d1002.1700000000.1a2b3c'
    expect(detectInterference(403, headers(), body)?.provider).toBe('Akamai')
  })

  it('detects an Imperva block page', () => {
    expect(detectInterference(403, headers(), 'Incapsula incident ID: 123-456')?.provider).toBe('Imperva')
  })

  it('detects a HUMAN challenge page', () => {
    expect(detectInterference(403, headers(), '<div id="px-captcha"></div>')).toEqual({
      status: 403,
      provider: 'HUMAN',
      reason: 'challenge',
    })
  })

  it('detects an F5 BIG-IP rejection page', () => {
    const body = 'The requested URL was rejected. Please consult with your administrator. Your support ID is: 123'
    expect(detectInterference(403, headers(), body)?.provider).toBe('F5 BIG-IP')
  })

  it('detects a Wordfence block page', () => {
    expect(detectInterference(503, headers(), '<p>Generated by Wordfence at Sat, 21 Nov</p>')?.provider).toBe('Wordfence')
  })

  it('detects a ModSecurity rejection', () => {
    expect(detectInterference(406, headers(), 'Not Acceptable! Mod_Security rejected the request.')?.provider).toBe(
      'ModSecurity',
    )
  })

  it('detects an application-level block message without a known provider', () => {
    const body = 'Requests from your network are temporarily blocked by our automated abuse-prevention system.'
    expect(detectInterference(403, headers({ server: 'cloudflare' }), body)).toEqual({
      status: 403,
      provider: null,
      reason: 'blocked',
    })
  })

  it('treats any 429 as rate limiting', () => {
    expect(detectInterference(429, headers(), '')).toEqual({
      status: 429,
      provider: null,
      reason: 'rate-limited',
    })
  })
})

describe('fetchPage', () => {
  afterEach(() => {
    vi.unstubAllGlobals()
  })

  it('returns the response, its body and any interference', async () => {
    vi.stubGlobal(
      'fetch',
      vi.fn(async () => new Response('checking your browser', { status: 403, headers: { 'cf-mitigated': 'challenge' } })),
    )

    const page = await fetchPage('https://example.com')

    expect(page?.body).toBe('checking your browser')
    expect(page?.response.status).toBe(403)
    expect(page?.interference).toEqual({ status: 403, provider: 'Cloudflare', reason: 'challenge' })
  })

  it('reports no interference when the page loads normally', async () => {
    vi.stubGlobal('fetch', vi.fn(async () => new Response('<html>ok</html>', { status: 200 })))

    expect((await fetchPage('https://example.com'))?.interference).toBeNull()
  })

  it('passes request options through', async () => {
    const fetchMock = vi.fn(async () => new Response('ok'))
    vi.stubGlobal('fetch', fetchMock)

    await fetchPage('https://example.com', { headers: { Origin: 'https://evil.com' } })

    expect(fetchMock.mock.calls[0][1]).toMatchObject({ headers: { Origin: 'https://evil.com' }, redirect: 'follow' })
  })

  it('returns null when the request fails', async () => {
    vi.stubGlobal(
      'fetch',
      vi.fn(async () => {
        throw new TypeError('fetch failed')
      }),
    )

    expect(await fetchPage('https://example.com')).toBeNull()
  })
})

describe('blockedResult', () => {
  it('marks the scanner as skipped with no findings', () => {
    expect(blockedResult('Headers')).toEqual({
      name: 'Headers',
      score: 0,
      findings: [],
      info: ['Not checked: the target blocked the scan'],
      skipped: true,
      skipReason: 'blocked',
    })
  })
})

describe('describeInterference', () => {
  it('names the provider and the kind of response', () => {
    expect(describeInterference({ status: 403, provider: 'Cloudflare', reason: 'challenge' })).toBe(
      'HTTP 403, Cloudflare challenge page',
    )
    expect(describeInterference({ status: 429, provider: null, reason: 'rate-limited' })).toBe('HTTP 429, rate limit')
    expect(describeInterference({ status: 403, provider: null, reason: 'blocked' })).toBe('HTTP 403, block page')
  })
})
